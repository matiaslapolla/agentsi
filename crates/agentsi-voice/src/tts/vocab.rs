static IDS: LazyLock<HashMap<char, i64>> = LazyLock::new(|| TABLE.iter().copied().collect());

/// The token id of a phoneme, or `None` when the model does not know it.
pub fn id(phoneme: char) -> Option<i64> {
    IDS.get(&phoneme).copied()
}

/// The phonemes that Kokoro reads: only known phonemes, one space between words, no edge space.
pub fn clean(raw: &str) -> String {
    let known: String = raw.chars().filter(|c| id(*c).is_some()).collect();
    known.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// The token ids of `phonemes`. Unknown phonemes are dropped.
pub fn tokens(phonemes: &str) -> Vec<i64> {
    phonemes.chars().filter_map(id).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_has_114_unique_phonemes() {
        assert_eq!(TABLE.len(), 114);
        assert_eq!(IDS.len(), 114);
    }

    #[test]
    fn clean_drops_unknown_phonemes_and_extra_space() {
        assert_eq!(clean("  həlˈoʊ\n  wˈɜːld_ "), "həlˈoʊ wˈɜːld");
        assert_eq!(tokens("a b"), vec![43, 16, 44]);
    }
}
